const assert = require('node:assert');
const L = require('./licences.js');

const check = (name, fn) => {
  try { fn(); console.log(`ok   - ${name}`); } catch (err) { console.error(`FAIL - ${name}`); console.error(err); process.exitCode = 1; }
};

check('Florida licence numbers compare without leading zeros; junk is null', () => {
  assert.deepStrictEqual(
    ['CGC061097', 'cgc 61097', 'EC13001234', '12AB0001', '0000000000', '', '1234567'].map(L.normalizeFlLicence),
    ['CGC61097', 'CGC61097', 'EC13001234', '12AB0001', null, null, null],
  );
});

check('US dates parse; anything else is missing, not guessed', () => {
  assert.deepStrictEqual(['08/31/2027', '8/1/2027', '2027-08-31', '13/45/2027', null].map(L.usDate), ['2027-08-31', '2027-08-01', null, null, null]);
});

check('CSV lines with quotes and commas inside fields', () => {
  assert.deepStrictEqual(L.parseCsvLine('"06","CGC","DOE, JOHN","ACME ""BEST"" BUILDERS",,x'), ['06', 'CGC', 'DOE, JOHN', 'ACME "BEST" BUILDERS', '', 'x']);
});

check('a DBPR row keys on the alternate licence number and keeps codes as published', () => {
  const f = ['06', 'CGC', 'DOE, JOHN', 'ACME BUILDERS INC', '01', '1 MAIN ST', '', '', 'MIAMI', 'FL', '33101', '23', '1512345',
    'C', 'A', '01/02/2010', '09/01/2024', '08/31/2026', '', '2', 'CGC061097', ''];
  const l = L.mapDbprRow(f);
  assert.deepStrictEqual([l.licenceKey, l.licenceType, l.primaryStatus, l.secondaryStatus, l.expiresOn, l.phone], ['CGC61097', 'CGC', 'C', 'A', '2026-08-31', null]);
  assert.strictEqual(L.mapDbprRow(f.slice(0, 10)), null);
});

check('TDLR: phones only for electrical contractors, never for A/C rows', () => {
  const ec = L.mapTdlrRow({ license_type: 'Electrical Contractor', license_number: '31234', business_name: 'SPARKY ELECTRIC LLC',
    business_telephone: '(512) 555-0142', business_city_state_zip: 'AUSTIN TX 78701', license_expiration_date_mmddccyy: '05/31/2027' });
  const ac = L.mapTdlrRow({ license_type: 'A/C Contractor', license_number: 'TACLB1', business_name: 'COOL AIR LLC', business_telephone: '5125550199' });
  assert.deepStrictEqual([ec.licenceKey, ec.phone, ec.city, ec.expiresOn], ['Electrical Contractor:31234', '+15125550142', 'AUSTIN', '2027-05-31']);
  assert.strictEqual(ac.phone, null);
  assert.strictEqual(L.mapTdlrRow({ license_type: 'Generated By: Public Information Act (PIA)', license_number: '1' }), null);
});

check('matching: licence number, then phone, then a unique name; people are matched by licence only', () => {
  const licences = [
    { licenceKey: 'CGC61097', businessName: 'ACME BUILDERS INC', phone: null },
    { licenceKey: 'Electrical Contractor:1', businessName: 'Sparky Electric LLC', phone: '+15125550142' },
    { licenceKey: 'Electrical Contractor:2', businessName: 'Twin Electric', phone: null },
    { licenceKey: 'Electrical Contractor:3', businessName: 'Twin Electric', phone: null },
  ];
  const cs = [
    { id: 1, identityKey: 'lic:FL:CGC061097', normalizedName: 'acme builders', state: 'FL', partyKind: 'business', phones: [] },
    { id: 2, identityKey: 'name:TX:sparky electric', normalizedName: 'sparky electric', state: 'TX', partyKind: 'business', phones: ['+15125550142'] },
    { id: 3, identityKey: 'name:TX:twin electric', normalizedName: 'twin electric', state: 'TX', partyKind: 'business', phones: [] },
    { id: 4, identityKey: 'name:TX:jane doe', normalizedName: 'sparky electric', state: 'TX', partyKind: 'individual', phones: ['+15125550142'] },
  ];
  const fl = L.matchLicences(cs, licences, 'FL').map((m) => [m.contractorId, m.licenceKey, m.rule]);
  const tx = L.matchLicences(cs, licences, 'TX').map((m) => [m.contractorId, m.licenceKey, m.rule]);
  assert.deepStrictEqual(fl, [[1, 'CGC61097', 'licence']]);
  // Sparky: phone and name both point at licence 1, recorded once (phone wins).
  // Twin: two licences share the name, so no match. The individual: nothing.
  assert.deepStrictEqual(tx, [[2, 'Electrical Contractor:1', 'phone']]);
});
